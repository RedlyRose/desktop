/* Markdown subset: ## heading, > quote, ![alt](src), **bold**, *em*, `code`. */
function blMd(src) {
  const inline = (s) => blEsc(s)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>');

  return String(src || '').split('\n').filter((l) => l.trim()).map((line) => {
    const l = line.trim();
    const img = /^!\[(.*?)\]\((.*?)\)$/.exec(l);
    if (img) {
      return `<figure class="bl-fig">
        <img src="${img[2]}" alt="${blEsc(img[1])}" loading="lazy">
      </figure>`;
    }
    if (l.startsWith('## ')) return `<h2 class="bl-heading"><span>${inline(l.slice(3))}</span></h2>`;
    if (l.startsWith('> ')) return `<blockquote class="bl-quote"><div class="bl-quote-icon">❝</div><p>${inline(l.slice(2))}</p></blockquote>`;
    return `<p>${inline(l)}</p>`;
  }).join('');
}

